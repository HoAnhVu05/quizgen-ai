/**
 * Trả về danh sách Khoa / Đơn vị tương ứng với trường được chọn
 */
export function getFacultiesForUniversity(univName: string): string[] {
  if (!univName || !univName.trim()) return GENERIC_DEFAULT_FACULTIES;
  const target = univName.toLowerCase().trim();
  const match = VIETNAMESE_UNIVERSITIES.find(
    (u) =>
      u.name.toLowerCase().includes(target) ||
      target.includes(u.name.toLowerCase()) ||
      u.shortName.toLowerCase() === target
  );
  return match && match.faculties && match.faculties.length > 0
    ? match.faculties
    : GENERIC_DEFAULT_FACULTIES;
}
