import React, { useCallback } from 'react';
import apiClient, { API_BASE } from '../../services/apiClient';
import { ScreenId, UserProfile, Question } from '../../types';
import {
  QuantaAction,
  SupportTicketActionData,
  ExamBlueprintActionData,
  PatchQuestionActionData,
  ImportExamActionData,
} from '../QuantaMarkdownRenderer';
import { ChatMessage } from './types';
import {
  extractFallbackImportQuestions,
  mapImportedQuestions,
  mapAutoGeneratedQuestions,
  saveImportedExamRecord,
  saveQuestionsToStorage,
  submitSupportTicketToApi,
} from './copilotActionHelpers';

interface UseCopilotActionsParams {
  currentScreen: ScreenId;
  screenLabel: string;
  currentUser: UserProfile | null;
  userHonorific: string;
  activeBook: any;
  activeQuestion?: Question | null;
  messages: ChatMessage[];
  setMessages: React.Dispatch<React.SetStateAction<ChatMessage[]>>;
  onNavigate?: (screen: ScreenId) => void;
  onGenerateSuccess?: (newQuestions: Question[], targetScreen?: ScreenId) => void;
  onUpdateQuestion?: (updated: Question) => void;
  onShowToast?: (type: 'success' | 'error' | 'warning' | 'info', title: string, message: string) => void;
}

export function useCopilotActions({
  currentScreen,
  screenLabel,
  currentUser,
  userHonorific,
  activeBook,
  activeQuestion,
  messages,
  setMessages,
  onNavigate,
  onGenerateSuccess,
  onUpdateQuestion,
  onShowToast,
}: UseCopilotActionsParams) {
  const handleSubmitSupportTicket = useCallback(
    async (ticketData: SupportTicketActionData) => {
      try {
        await submitSupportTicketToApi({
          ticketData,
          currentScreen,
          screenLabel,
          currentUser,
          userHonorific,
        });

        onShowToast?.(
          'success',
          'Đã gửi phiếu hỗ trợ thành công',
          ticketData.files && ticketData.files.length > 0
            ? `Đã gửi kèm ${ticketData.files.length} ảnh biên lai/chứng từ tới Ban Quản Trị.`
            : 'Admin sẽ tiếp nhận và phản hồi sớm nhất.'
        );
        return true;
      } catch (e) {
        console.error('Lỗi gửi ticket:', e);
        return false;
      }
    },
    [currentScreen, screenLabel, currentUser, userHonorific, onShowToast]
  );

  const handlePatchQuestion = useCallback(
    async (patchData: PatchQuestionActionData) => {
      try {
        if (!patchData || !patchData.questionId) return false;

        const savedQuestions: Question[] = JSON.parse(
          localStorage.getItem('quizgen_questions') ||
            localStorage.getItem('quizgen_pending_review_questions') ||
            '[]'
        );

        const targetQ =
          savedQuestions.find((q) => q.id === patchData.questionId) ||
          (activeQuestion?.id === patchData.questionId ? activeQuestion : null);

        if (!targetQ) {
          onShowToast?.(
            'warning',
            'Không tìm thấy câu hỏi',
            `Không tìm thấy câu hỏi ID ${patchData.questionId} để cập nhật.`
          );
          return false;
        }

        const patch = patchData.patch || {};
        const updatedQ: Question = {
          ...targetQ,
          question: patch.question || targetQ.question,
          options:
            patch.options && patch.options.length > 0
              ? patch.options.map((o) => ({ id: o.id, label: o.label || o.id, text: o.text }))
              : targetQ.options,
          correctAnswerId: patch.correctAnswerId || targetQ.correctAnswerId,
          explanation: patch.explanation || targetQ.explanation,
          bloomLevel: (patch.bloomLevel as any) || targetQ.bloomLevel,
        };

        onUpdateQuestion?.(updatedQ);

        const updatedList = savedQuestions.map((q) => (q.id === updatedQ.id ? updatedQ : q));
        if (!savedQuestions.some((q) => q.id === updatedQ.id)) {
          updatedList.unshift(updatedQ);
        }
        saveQuestionsToStorage(updatedList);

        try {
          await apiClient.fetch(`${API_BASE}/questions/${updatedQ.id}`, {
            method: 'PUT',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(updatedQ),
          });
        } catch (dbErr) {
          console.warn('Lỗi đồng bộ CSDL questions PUT:', dbErr);
        }

        onShowToast?.(
          'success',
          'Quanta đã cập nhật câu hỏi!',
          patchData.diffSummary || `Đã cập nhật câu hỏi ${updatedQ.id} thành công.`
        );

        setMessages((prev) => [
          ...prev,
          {
            id: `msg-${Date.now()}`,
            role: 'assistant',
            content:
              `✅ Quanta đã cập nhật trực tiếp câu hỏi **${updatedQ.id}** vào bộ đề tại Bước 3 theo yêu cầu của Thầy/Cô!\n\n` +
              `• **Đáp án đúng:** Phương án ${updatedQ.correctAnswerId}\n` +
              `• **Mức độ Bloom:** ${updatedQ.bloomLevel}\n\n` +
              `Thầy/Cô có thể kiểm tra ngay trong Không gian Thẩm định.`,
            timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
          },
        ]);

        return true;
      } catch (e) {
        console.error('Lỗi khi Quanta patch câu hỏi:', e);
        return false;
      }
    },
    [activeQuestion, onUpdateQuestion, onShowToast, setMessages]
  );

  const handleImportExam = useCallback(
    async (importData: ImportExamActionData, targetScreen: ScreenId = 'bank') => {
      try {
        if (!importData || !importData.questions || importData.questions.length === 0) return false;

        const targetDocName = activeBook?.name || 'Giáo trình Quanta AI';
        const mappedQuestions = mapImportedQuestions(
          importData.questions,
          targetDocName,
          targetScreen === 'bank' ? 'approved' : 'pending'
        );

        const existing: Question[] = JSON.parse(
          localStorage.getItem('quizgen_questions') ||
            localStorage.getItem('quizgen_pending_review_questions') ||
            '[]'
        );
        const combined = [
          ...mappedQuestions,
          ...existing.filter((eq) => !mappedQuestions.some((mq) => mq.id === eq.id)),
        ];
        saveQuestionsToStorage(combined);

        if (targetScreen === 'bank') {
          saveImportedExamRecord(mappedQuestions, importData.title, targetDocName, currentUser);
        }

        onGenerateSuccess?.(combined, targetScreen);
        onNavigate?.(targetScreen);
        onShowToast?.(
          'success',
          'Quanta đã nạp đề thi thành công!',
          `Đã nạp ${mappedQuestions.length} câu hỏi vào ${
            targetScreen === 'bank' ? 'Bước 4 (In ấn & Ngân hàng đề)' : 'Bước 3 (Thẩm định)'
          }.`
        );

        setMessages((prev) => [
          ...prev,
          {
            id: `msg-import-${Date.now()}`,
            role: 'assistant',
            content:
              `✅ Quanta đã nạp thành công **${mappedQuestions.length} câu hỏi** vào **${
                targetScreen === 'bank' ? 'Bước 4: Ngân hàng đề & In đề' : 'Bước 3: Không gian Thẩm định'
              }** theo yêu cầu của Thầy/Cô!\n\n` +
              `• **Đề thi:** ${importData.title || 'Bộ đề thi Quanta AI'}\n` +
              `• **Số lượng câu hỏi:** ${mappedQuestions.length} câu đã sẵn sàng tạo mã đề (101, 102...) và xuất bản in A4 / file Word (.docx) / phiếu OMR.\n\n` +
              `*Hệ thống đã tự động chuyển màn hình sang Bước ${targetScreen === 'bank' ? '4' : '3'} để Thầy/Cô thao tác ngay ạ!*`,
            timestamp: new Date().toLocaleTimeString('vi-VN', { hour: '2-digit', minute: '2-digit' }),
            suggestedActions:
              targetScreen === 'bank'
                ? ['🖨️ Xuất file Word (.docx)', '📋 Tạo mã đề hoán vị', '📝 Quay lại duyệt Bước 3']
                : ['🚀 Chuyển sang Bước 4 in đề', '💡 Đổi câu hỏi khó hơn', '📊 Xem thống kê Bloom'],
          },
        ]);

        return true;
      } catch (e) {
        console.error('Lỗi khi Quanta import đề thi:', e);
        return false;
      }
    },
    [activeBook, currentUser, onGenerateSuccess, onNavigate, onShowToast, setMessages]
  );

  const handleAutoGenerateExam = useCallback(
    async (blueprint: ExamBlueprintActionData) => {
      try {
        localStorage.setItem(
          'quizgen_pending_exam_blueprint',
          JSON.stringify({ ...blueprint, createdAt: Date.now() })
        );
      } catch {}

      const targetDocName = blueprint.documentName || activeBook?.name || 'Giáo trình Kỹ thuật đồ họa - 2018';
      const targetDocId = blueprint.documentId || activeBook?.id || 'tb-039';
      const count = Number(blueprint.questionCount || 20);
      const ratio = blueprint.bloomRatio || { know: 30, understand: 40, apply: 20, analyze: 10 };

      const nb = Math.round((count * (ratio.know || 25)) / 100);
      const th = Math.round((count * (ratio.understand || 25)) / 100);
      const vd = Math.round((count * (ratio.apply || 25)) / 100);
      const vdc = Math.max(0, count - nb - th - vd);

      const loadingMsgId = `bot-loading-${Date.now()}`;
      setMessages((prev) => [
        ...prev,
        {
          id: loadingMsgId,
          role: 'assistant',
          content:
            `⏳ **Quanta đang kích hoạt quy trình sinh đề thi tự động:**\n\n` +
            `• 📖 **Giáo trình:** *${targetDocName}*\n` +
            `• 📑 **Chương:** *${blueprint.chapter || 'Chương 2: Các thuật toán cơ sở và Phép biến đổi hình học 2D/3D'}*\n` +
            `• 📊 **Quy mô ma trận:** ${count} câu hỏi (Nhận biết: ${nb}, Thông hiểu: ${th}, Vận dụng: ${vd}, Vận dụng cao: ${vdc})\n\n` +
            `*Quanta đang nạp ngữ cảnh trích đoạn và gọi Gemini AI sinh đề trắc nghiệm thật sự... Vui lòng đợi trong giây lát ạ!*`,
          timestamp: new Date().toLocaleTimeString('vi-VN', { hour: '2-digit', minute: '2-digit' }),
        },
      ]);

      try {
        const token = localStorage.getItem('quizgen_auth_token') || sessionStorage.getItem('quizgen_token');
        const headers: Record<string, string> = { 'Content-Type': 'application/json' };
        if (token) headers['Authorization'] = `Bearer ${token}`;

        const payload = {
          documentId: targetDocId,
          document_id: targetDocId,
          documentName: targetDocName,
          document_name: targetDocName,
          chapters: blueprint.chapter ? [blueprint.chapter] : [],
          bloomMatrix: { nhanBiet: nb, thongHieu: th, vanDung: vd, phanTich: vdc },
          bloom_matrix: { nhanBiet: nb, thongHieu: th, vanDung: vd, phanTich: vdc },
          pedagogicalPrompt: 'Sinh câu hỏi trắc nghiệm chất lượng cao bám sát giáo trình',
        };

        const res = await apiClient.fetch(`${API_BASE}/ai/generate`, {
          method: 'POST',
          headers,
          body: JSON.stringify(payload),
        });

        if (!res.ok) throw new Error(`AI Service phản hồi mã ${res.status}`);

        const data = await res.json();
        const rawList: any[] = Array.isArray(data) ? data : Array.isArray(data?.questions) ? data.questions : [];
        if (rawList.length === 0) throw new Error('AI không trả về danh sách câu hỏi phù hợp.');

        const mappedQuestions = mapAutoGeneratedQuestions(rawList, targetDocName, blueprint.chapter);

        onGenerateSuccess?.(mappedQuestions);
        saveQuestionsToStorage(mappedQuestions);

        onShowToast?.('success', 'Quanta sinh đề thành công!', `Đã sinh thành công ${mappedQuestions.length} câu hỏi mới.`);

        setMessages((prev) => [
          ...prev.filter((m) => m.id !== loadingMsgId),
          {
            id: `bot-done-${Date.now()}`,
            role: 'assistant',
            content:
              `🎉 **Quanta đã sinh thành công bộ đề thi mới gồm ${mappedQuestions.length} câu hỏi!**\n\n` +
              `• **Tài liệu nguồn:** *${targetDocName}*\n` +
              `• **Số lượng câu hỏi mới:** ${mappedQuestions.length} câu đã được tải vào Không gian Đối soát.\n\n` +
              `*Em đã đưa Thầy/Cô sang Bước 3 (Đối soát & Biên tập) để kiểm duyệt đáp án và giải thích chi tiết ngay ạ!*`,
            timestamp: new Date().toLocaleTimeString('vi-VN', { hour: '2-digit', minute: '2-digit' }),
            suggestedActions: ['💡 Đổi câu hỏi khó hơn', '📊 Xem thống kê ma trận', '🖨️ Sang Bước 4: Xuất đề Word'],
          },
        ]);

        onNavigate?.('review');
      } catch (err: any) {
        console.error('Lỗi sinh đề từ Quanta:', err);
        setMessages((prev) => [
          ...prev.filter((m) => m.id !== loadingMsgId),
          {
            id: `bot-err-${Date.now()}`,
            role: 'assistant',
            content:
              `⚠️ **Quanta không thể tự động sinh đề do:** ${err.message || 'Lỗi kết nối AI Service'}.\n\n` +
              `Thầy/Cô có thể bấm nút **Tự chỉnh** ở trên để chuyển sang Bước 2 và tự bấm sinh đề với cấu hình này ạ!`,
            timestamp: new Date().toLocaleTimeString('vi-VN', { hour: '2-digit', minute: '2-digit' }),
            suggestedActions: ['⚙️ Mở Bước 2: Tự chỉnh', '🎧 Báo lỗi kỹ thuật'],
          },
        ]);
      }
    },
    [activeBook, onGenerateSuccess, onNavigate, onShowToast, setMessages]
  );

  const processStructuredOrFallbackActions = useCallback(
    (userText: string, replyContent: string, structuredActions?: QuantaAction[]) => {
      const actionsList = Array.isArray(structuredActions) ? structuredActions : [];
      const ticketAct = actionsList.find((a) => a.type === 'support_ticket');
      if (ticketAct?.data) {
        setTimeout(() => void handleSubmitSupportTicket(ticketAct.data as SupportTicketActionData), 250);
      } else {
        const ticketMatch = /```action:support_ticket\s*([\s\S]*?)```/.exec(replyContent);
        if (ticketMatch) {
          try {
            const ticketPayload: SupportTicketActionData = JSON.parse(ticketMatch[1].trim());
            setTimeout(() => void handleSubmitSupportTicket(ticketPayload), 250);
          } catch {}
        }
      }

      const isAutoRequested = /nạp|đưa vào|chuyển qua|vào bước 4|vào bước 3|in đề|xuất đề/i.test(userText);
      const importAct = actionsList.find((a) => a.type === 'import_exam');
      if (importAct?.data) {
        const importPayload = importAct.data as ImportExamActionData;
        if (isAutoRequested || importPayload.autoExecute) {
          const targetScreen = /bước 3|duyệt|thẩm định/i.test(userText) ? 'review' : importPayload.targetScreen || 'bank';
          setTimeout(() => void handleImportExam(importPayload, targetScreen), 400);
        }
        return;
      }

      const importMatch = /```action:import_exam\s*([\s\S]*?)```/.exec(replyContent);
      if (importMatch) {
        try {
          const importPayload: ImportExamActionData = JSON.parse(importMatch[1].trim());
          if (isAutoRequested || importPayload.autoExecute) {
            const targetScreen = /bước 3|duyệt|thẩm định/i.test(userText)
              ? 'review'
              : importPayload.targetScreen || 'bank';
            setTimeout(() => void handleImportExam(importPayload, targetScreen), 400);
          }
        } catch {}
      } else if (isAutoRequested) {
        const foundQs = extractFallbackImportQuestions(replyContent, messages);
        if (foundQs.length > 0) {
          const fallbackPayload: ImportExamActionData = {
            title: 'Bộ Đề Khảo Thí Quanta Trích Xuất',
            targetScreen: /bước 3|duyệt|thẩm định/i.test(userText) ? 'review' : 'bank',
            questions: foundQs,
          };
          setTimeout(() => void handleImportExam(fallbackPayload, fallbackPayload.targetScreen || 'bank'), 400);
        }
      }
    },
    [handleSubmitSupportTicket, handleImportExam, messages]
  );

  return {
    handleSubmitSupportTicket,
    handlePatchQuestion,
    handleImportExam,
    handleAutoGenerateExam,
    processStructuredOrFallbackActions,
  };
}
